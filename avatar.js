/**
 * Henter SVG-streng for en gitt avatar-ID.
 * @param {string} avatarId 
 * @returns {string} SVG-streng
 */
function getAvatarSvg(avatarId) {
  return AVATARS[avatarId]?.svg || "";
}

/**
 * Renderer en avatar direkte inn i et HTML-element.
 * @param {string} avatarId 
 * @param {HTMLElement|string} targetElement (Element eller CSS-selektor)
 * @returns {boolean} True hvis rendring var vellykket
 */
function renderAvatar(avatarId, targetElement) {
  const container = typeof targetElement === "string" 
    ? document.querySelector(targetElement) 
    : targetElement;

  if (!container) {
    console.warn(`renderAvatar: Finner ikke elementet "${targetElement}".`);
    return false;
  }

  if (!AVATARS[avatarId]) {
    console.warn(`renderAvatar: Ugyldig avatar-ID "${avatarId}".`);
    return false;
  }

  container.innerHTML = AVATARS[avatarId].svg;
  return true;
}